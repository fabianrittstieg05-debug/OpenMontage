#!/usr/bin/env python3
"""Generate the `.claude/skills/` pointer stubs from the canonical Layer 3 skills.

`.agents/skills/` is the single source of truth for Layer 3 knowledge. It is
what `tools/base_tool.py` documents for `agent_skills`, what
`tests/contracts/test_agent_skill_pointers.py` resolves pointers against, and
what `npx skills add` writes into.

Claude Code, however, only auto-discovers skills under `.claude/skills/<name>/
SKILL.md`. That used to be satisfied by copying the whole skill tree in, which
duplicated 428 files and had already drifted (`ai-video-gen` lost a provider,
`elevenlabs` lost the shared-installation routing rules).

Symlinks are the obvious fix and are what `skills/INDEX.md` used to claim, but
they are not reliable for skill discovery -- the desktop app skips symlinked
skill directories, and a Windows checkout without `core.symlinks` materializes
them as text files containing a path. So `.claude/skills/` keeps real files,
reduced to a stub per skill:

    canonical frontmatter (verbatim)  ->  preserves name/description/allowed-tools
    pointer body                      ->  sends the agent to the canonical file

The frontmatter is what Claude Code reads to decide *when* to invoke a skill, so
copying it verbatim keeps triggering identical. The body is the only thing that
changes, and it routes to `.agents/skills/` -- the same Layer 3 read that
AGENT_GUIDE.md already mandates before calling any generation tool.

Usage:
    python scripts/sync_claude_skills.py           # regenerate the stubs
    python scripts/sync_claude_skills.py --check    # verify, exit 1 on drift
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CANONICAL_ROOT = REPO_ROOT / ".agents" / "skills"
EXPOSED_ROOT = REPO_ROOT / ".claude" / "skills"

GENERATED_MARKER = "<!-- GENERATED by scripts/sync_claude_skills.py -- do not edit."

# Skills exposed to Claude Code as project skills, as
