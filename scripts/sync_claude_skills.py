def read_frontmatter(skill_md: Path) -> str:
    """Return the frontmatter block verbatim, without the `---` fences.

    Verbatim and not parsed-then-dumped on purpose: 14 of these skills use a
    block-scalar `description`, 7 carry `allowed-tools`, and others carry
    `metadata` / `license` / `compatibility` / `homepage`. Reserializing risks
    changing the text Claude Code matches against, or dropping a field that
    governs tool access.
    """
    lines = skill_md.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{skill_md} does not start with a '---' frontmatter fence")
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            body = "\n".join(lines[1:index]).rstrip()
            if "description:" not in body or "name:" not in body:
                raise ValueError(f"{skill_md} frontmatter lacks name/description")
            return body
    raise ValueError(f"{skill_md} has no closing '---' frontmatter fence")


def describe_bundle(canonical_dir: Path) -> list[str]:
    """Summarize what else ships with the skill, so the stub can point at it."""
    entries: list[str] = []
    for child in sorted(canonical_dir.iterdir()):
        if child.name == "SKILL.md":
            continue
        if child.name.startswith(".") or child.name == "__pycache__":
            continue
        if child.is_dir():
            count = sum(1 for p in child.rglob("*") if p.is_file())
            entries.append(f"`{child.name}/` ({count} file{'s' if count != 1 else ''})")
        else:
            entries.append(f"`{child.name}`")
    return entries


def render_stub(directory: str, canonical: str) -> str:
    canonical_dir = CANONICAL_ROOT / canonical
    skill_md = canonical_dir / "SKILL.md"
    frontmatter = read_frontmatter(skill_md)
    bundle = describe_bundle(canonical_dir)

    lines = [
        "---",
        frontmatter,
        "---",
        "",
        GENERATED_MARKER,
        f"     Canonical skill: .agents/skills/{canonical}/SKILL.md",
        "     Regenerate: python scripts/sync_claude_skills.py -->",
        "",
        f"# Pointer: `.agents/skills/{canonical}/`",
        "",
        f"**Read `.agents/skills/{canonical}/SKILL.md` before doing anything else.**",
        "That file is this skill; everything below the frontmatter here is just a",
        "pointer to it, and acting on this stub alone means acting without the",
        "skill's actual instructions.",
        "",
        "The canonical copy lives under `.agents/skills/` because that is the Layer 3",
        "store that `agent_skills` pointers, the registry, and `npx skills add` all",
        "use. Keeping one copy is what stops the two trees from drifting apart.",
    ]

    if bundle:
        lines += [
            "",
            f"Bundled with it in `.agents/skills/{canonical}/`, to read as the skill directs:",
            "",
        ]
        lines += [f"- {entry}" for entry in bundle]

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the stubs match the canonical skills; exit 1 on drift",
    )
    args = parser.parse_args()

    problems: list[str] = []
    written = 0

    for directory, canonical in sorted(EXPOSED_SKILLS.items()):
        canonical_md = CANONICAL_ROOT / canonical / "SKILL.md"
        if not canonical_md.exists():
            problems.append(
                f"{directory}: canonical .agents/skills/{canonical}/SKILL.md is missing"
            )
            continue

        expected = render_stub(directory, canonical)
        target = EXPOSED_ROOT / directory / "SKILL.md"

        if args.check:
            if not target.exists():
                problems.append(f"{directory}: .claude/skills/{directory}/SKILL.md is missing")
            elif target.read_text(encoding="utf-8") != expected:
                problems.append(
                    f"{directory}: stub is out of sync with "
                    f".agents/skills/{canonical}/SKILL.md"
                )
            continue

        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            target.write_text(expected, encoding="utf-8")
            written += 1

    # A stray directory is a real problem in --check: it is either a skill some
    # tool still expects, or leftover duplication that will drift again.
    if EXPOSED_ROOT.exists():
        for child in sorted(EXPOSED_ROOT.iterdir()):
            if child.is_dir() and child.name not in EXPOSED_SKILLS:
                problems.append(
                    f"{child.name}: present in .claude/skills/ but not in EXPOSED_SKILLS"
                )

    if problems:
        header = "Skill stubs are out of sync:" if args.check else "Problems:"
        print(header, file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        if args.check:
            print(
                "\nRun: python scripts/sync_claude_skills.py",
                file=sys.stderr,
            )
        return 1

    if args.check:
        print(f"{len(EXPOSED_SKILLS)} skill stubs in sync with .agents/skills/")
    else:
        print(
            f"{len(EXPOSED_SKILLS)} skill stubs generated "
            f"({written} changed) from .agents/skills/"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
